/**
 * Generates remotion/components/defs.ts and registry.tsx from the component folders.
 *   npm run gen
 * A folder counts as a component if it contains def.ts and <Name>.tsx.
 */
import fs from 'node:fs';
import path from 'node:path';
import { log, main } from './lib/log';
import { ROOT } from './lib/paths';
import type { ComponentMeta } from '../remotion/components/types';

main(async () => {
  const dir = path.join(ROOT, 'remotion', 'components');
  const names = fs
    .readdirSync(dir)
    .filter((n) => /^[A-Z]/.test(n) && fs.statSync(path.join(dir, n)).isDirectory())
    .filter((n) => fs.existsSync(path.join(dir, n, 'def.ts')) && fs.existsSync(path.join(dir, n, `${n}.tsx`)))
    .sort();
  const head = '// GENERATED by `npm run gen` – do not edit by hand.\n';
  fs.writeFileSync(
    path.join(dir, 'defs.ts'),
    head +
      names.map((n) => `import * as ${n} from './${n}/def';`).join('\n') +
      `\n\nexport const defs = {\n${names.map((n) => `  ${n},`).join('\n')}\n};\n` +
      `export type ComponentName = keyof typeof defs;\n` +
      `export const componentNames = Object.keys(defs) as ComponentName[];\n` +
      `export const isComponentName = (n: string): n is ComponentName => n in defs;\n`,
  );
  fs.writeFileSync(
    path.join(dir, 'registry.tsx'),
    head +
      `import type React from 'react';\nimport type { ComponentName } from './defs';\n` +
      names.map((n) => `import { ${n} } from './${n}/${n}';`).join('\n') +
      `\n\n// eslint-disable-next-line @typescript-eslint/no-explicit-any\nexport const registry: Record<ComponentName, React.FC<any>> = {\n${names.map((n) => `  ${n},`).join('\n')}\n};\n`,
  );
  // Overview for Claude (edit planning): one row per component from def.ts + meta.md
  const { defs } = (await import(path.join(dir, 'defs.ts'))) as { defs: Record<string, { meta: ComponentMeta }> };
  const groups = ['Cards', 'Media', 'Overlays'] as const;
  const purpose = (n: string) => {
    const md = fs.readFileSync(path.join(dir, n, 'meta.md'), 'utf8');
    const title = md.split('\n').find((l) => l.startsWith('# '))?.replace(/^#\s*/, '') ?? n;
    return title.includes('–') ? title.split('–').slice(1).join('–').trim() : title;
  };
  const lines = [
    '# Component catalog',
    '',
    'GENERATED by `npm run gen`. Details, rules and props per component: `remotion/components/<Name>/meta.md`.',
    'Stills: `brand/catalog/<Name>-16x9.png` / `-9x16.png` (`npm run catalog`).',
    '',
    '16:9 layouts: **split** = panel on the left next to the speaker · **full** = full frame · **overlay** = on top of the speaker.',
    '9:16: **stage** = card on a light surface (split: graphic on top, speaker below; full: centered) · **native** = built for portrait · **overlay** · – = not for Shorts.',
    '',
  ];
  for (const g of groups) {
    const inGroup = names.filter((n) => defs[n]?.meta.group === g);
    if (!inGroup.length) continue;
    lines.push(`## ${g}`, '', '| Component | Purpose | 16:9 | 9:16 | Duration |', '|---|---|---|---|---|');
    for (const n of inGroup) {
      const m = defs[n].meta;
      lines.push(`| ${n} | ${purpose(n)} | ${m.layouts.join(', ')} | ${m.portrait || '–'} | ${m.minSeconds ? `≥ ${m.minSeconds} s, ` : ''}${m.seconds} s |`);
    }
    lines.push('');
  }
  fs.writeFileSync(path.join(dir, 'CATALOG.md'), lines.join('\n'));
  log.ok(`${names.length} components registered, CATALOG.md updated`);
});
