/**
 * Applies your own brand: channel name, language, accent color, logo, avatar, font.
 * Every flag is optional – pass only what should change. Used by the /welcome skill.
 *   npm run brand -- --name "My Channel" --language de --accent "#E8590C"
 *   npm run brand -- --logo ~/Desktop/logo.svg [--logo-white ~/Desktop/logo-white.svg] | --no-logo
 *   npm run brand -- --avatar ~/Desktop/profile.jpg
 *   npm run brand -- --font "Manrope" --font-files ~/Downloads/Manrope/
 *   … --dry-run   shows what would change, writes nothing
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseCli } from './lib/cli';
import { hasBinary, runOrThrow } from './lib/exec';
import { log, main } from './lib/log';
import { BRAND, readJson, rootRel, writeJson } from './lib/paths';

const USAGE =
  'npm run brand -- [--name "<channel>"] [--language <code>] [--accent "#RRGGBB"] [--logo <file> [--logo-white <file>] | --no-logo] ' +
  '[--avatar <file>] [--font "<family>"] [--font-files <dir|file> …] [--dry-run]';

const EXAMPLE_NAME = 'Example Brand';
const GENERATED = '<!-- generated by npm run brand -->';
const LOGOS = path.join(BRAND, 'logos');
/** The shipped placeholder files: mark (rounded bar with a play triangle) and/or the stretched text wordmark */
const PLACEHOLDER_LOGO = /M15 30 L36 50 L15 70 Z|lengthAdjust='spacingAndGlyphs'/;
const PLACEHOLDER_AVATAR = 'M118 106 L140 128 L118 150 Z';
const FONTS = path.join(BRAND, 'fonts');
const FONT_EXT = ['.woff2', '.woff', '.ttf', '.otf'];
const IMAGE_MIME: Record<string, string> = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };

type BrandJson = Record<string, any>;
type Action = { what: string; apply: () => void };

main(async () => {
  const { values, positionals } = parseCli(USAGE, {
    name: { type: 'string' },
    language: { type: 'string' },
    accent: { type: 'string' },
    logo: { type: 'string' },
    'logo-white': { type: 'string' },
    'no-logo': { type: 'boolean', default: false },
    avatar: { type: 'string' },
    font: { type: 'string' },
    'font-files': { type: 'string', multiple: true },
    'dry-run': { type: 'boolean', default: false },
  });
  const dry = values['dry-run'];
  const brandFile = path.join(BRAND, 'brand.json');
  const brand = readJson<BrandJson>(brandFile);
  const before = JSON.stringify(brand);
  const actions: Action[] = [];
  const write = (file: string, content: string | Buffer, what: string) =>
    actions.push({ what: `${rootRel(file)} – ${what}`, apply: () => fs.writeFileSync(file, content) });

  // `--font-files a.ttf b.ttf` (or a shell glob): everything after the first file arrives as a positional
  if (positionals.length && !values['font-files']) throw new Error(`Unexpected argument "${positionals[0]}".\n  ${USAGE}`);
  if (values.logo && values['no-logo']) throw new Error('--logo and --no-logo exclude each other.');
  if (values['logo-white'] && !values.logo) throw new Error('--logo-white only together with --logo.');

  // ── channel ──
  brand.channel ??= { name: 'Your Channel', language: 'en' };
  brand.logo ??= { enabled: true, sting: true };
  if (values.name !== undefined) {
    const name = values.name.trim();
    if (!name) throw new Error('--name is empty.');
    brand.name = name;
    brand.channel.name = name;
    if (name.length > 24) log.warn(`"${name}" has ${name.length} characters – the SubscribeButton shows at most 24; pass a shorter channel prop there.`);
  }
  if (values.language !== undefined) {
    if (!/^[a-z]{2,3}(-[A-Za-z]{2,4})?$/.test(values.language)) throw new Error(`--language "${values.language}" is not a language code (e.g. en, de, pt-BR).`);
    brand.channel.language = values.language;
  }

  // ── accent ──
  if (values.accent !== undefined) {
    const accent = normalizeHex(values.accent);
    const scale = primaryScale(accent);
    brand.colors.primary = scale;
    brand.look.brand = accent;
    brand.look.bar = `linear-gradient(90deg, ${scale['200']} 0%, ${accent} 100%)`;
    brand.look.stage = `linear-gradient(180deg, ${brand.look.surface} 0%, ${scale['50']} 100%)`;
  }

  // ── logo ──
  if (values['no-logo']) {
    brand.logo = { enabled: false, sting: false };
  } else if (values.logo) {
    const svg = await toSvg(values.logo);
    const white = values['logo-white'] ? await toSvg(values['logo-white']) : svg;
    for (const v of ['accent', 'dark']) write(path.join(LOGOS, `logo-${v}.svg`), svg, `from ${path.basename(values.logo)}`);
    write(path.join(LOGOS, 'logo-white.svg'), white, `from ${path.basename(values['logo-white'] ?? values.logo)}`);
    // The Sting animates mark + wordmark of the placeholder geometry – it does not fit an arbitrary logo.
    brand.logo = { enabled: true, sting: false };
  } else if (brand.logo.enabled && (values.name !== undefined || values.accent !== undefined)) {
    // Still the shipped placeholder logo: follow the new accent and name, so Sting and EndCard don't show a blue "Your Brand".
    const oldAccent = (JSON.parse(before) as BrandJson).look.brand;
    const label = brand.channel.name;
    const fitsWordmark = label.length >= 5 && label.length <= 18; // the wordmark is stretched to a fixed width
    let placeholder = false;
    for (const kind of ['logo', 'mark', 'wordmark']) {
      for (const variant of ['accent', 'white', 'dark']) {
        const file = path.join(LOGOS, `${kind}-${variant}.svg`);
        const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
        if (!PLACEHOLDER_LOGO.test(current)) continue;
        placeholder = true;
        let next = current;
        if (variant === 'accent' && values.accent !== undefined) next = next.split(oldAccent).join(brand.look.brand);
        if (values.name !== undefined && fitsWordmark) next = next.replace(/(<text\b[^>]*>)[^<]*(<\/text>)/, (_m, a: string, z: string) => `${a}${escapeXml(label)}${z}`);
        if (next !== current) write(file, next, 'placeholder logo updated');
      }
    }
    if (placeholder) {
      if (values.name !== undefined && !fitsWordmark) log.warn(`The placeholder logo keeps its old text – "${label}" is too ${label.length < 5 ? 'short' : 'long'} for its fixed width.`);
      log.warn('The logo is still the placeholder (mark + channel name as text). Pass --logo <file> for your own, or --no-logo.');
    }
  }

  // ── avatar ──
  const avatarFile = path.join(LOGOS, 'channel-avatar.svg');
  if (values.avatar) {
    write(avatarFile, await toSvg(values.avatar, { square: true }), `from ${path.basename(values.avatar)}`);
  } else if (values.name !== undefined || values.accent !== undefined) {
    // No picture given: initial on an accent circle (like YouTube) – but never overwrite a real avatar.
    const current = fs.existsSync(avatarFile) ? fs.readFileSync(avatarFile, 'utf8') : '';
    const replaceable = !current || current.includes(GENERATED) || current.includes(PLACEHOLDER_AVATAR) || (values.name !== undefined && JSON.parse(before).name === EXAMPLE_NAME);
    if (replaceable) write(avatarFile, initialAvatar(brand.channel.name, brand.look.brand), `initial "${initialOf(brand.channel.name)}" on ${brand.look.brand}`);
  }

  // ── font ──
  if (values['font-files']) {
    const files = [...values['font-files'], ...positionals].flatMap((p) => {
      const abs = path.resolve(expandHome(p));
      if (!fs.existsSync(abs)) throw new Error(`Not found: ${p}`);
      return fs.statSync(abs).isDirectory() ? fs.readdirSync(abs).map((f) => path.join(abs, f)) : [abs];
    }).filter((f) => FONT_EXT.includes(path.extname(f).toLowerCase()) && !path.basename(f).startsWith('._'));
    if (!files.length) throw new Error(`No font files (${FONT_EXT.join(', ')}) found in --font-files.`);
    const old = fontFiles();
    if (old.length) actions.push({ what: `brand/fonts/ – remove ${old.length} old font file(s)`, apply: () => old.forEach((f) => fs.rmSync(path.join(FONTS, f))) });
    for (const f of files) {
      const dest = path.join(FONTS, path.basename(f));
      actions.push({ what: `${rootRel(dest)} – copied`, apply: () => fs.copyFileSync(f, dest) });
    }
    const weights = new Set(files.map((f) => weightOf(path.basename(f))));
    const missing = weights.has('100 900') ? [] : ['500', '600', '700'].filter((w) => !weights.has(w));
    if (missing.length) log.warn(`Font weights ${missing.join(', ')} missing – the components use 500, 600 and 700 (a variable font covers all).`);
    if (!values.font) log.warn('--font-files without --font: the files are loaded under the current family "' + brand.typography.family + '".');
  }
  if (values.font !== undefined) {
    brand.typography.family = values.font.trim();
    if (!values['font-files'] && fontFiles().length) {
      log.warn(`brand/fonts/ still holds ${fontFiles().length} file(s) – they are loaded under "${brand.typography.family}". Replace them with --font-files.`);
    }
  }

  // ── brand.json ──
  const { name, source, channel, logo, ...rest } = brand;
  const next = { name, source, channel, logo, ...rest };
  if (JSON.stringify(next) !== before) {
    actions.unshift({ what: `brand/brand.json – ${describe(JSON.parse(before), next)}`, apply: () => writeJson(brandFile, next) });
  }

  if (!actions.length) {
    log.info('Nothing to change.');
    log.dim(`Usage: ${USAGE}`);
    return;
  }
  log.step(dry ? 'Would change (dry run, nothing written)' : 'Brand');
  for (const a of actions) {
    if (!dry) a.apply();
    (dry ? log.info : log.ok)(a.what);
  }
  if (!next.logo.enabled) log.info('No logo: the end card shows none, the Sting is not used.');
  else if (!next.logo.sting) log.info('Own logo: the Sting (logo animation) is off – it is built for the placeholder logo.');
  if (!dry) log.info('Next: npm run catalog -- EndCard   (stills in brand/catalog/)');
});

// ── helpers ──

function expandHome(p: string): string {
  return p.startsWith('~/') ? path.join(process.env.HOME ?? '', p.slice(2)) : p;
}

function normalizeHex(v: string): string {
  const m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(v.trim());
  if (!m) throw new Error(`--accent "${v}" is not a hex color (e.g. #E8590C).`);
  const h = m[1].length === 3 ? [...m[1]].map((c) => c + c).join('') : m[1];
  return `#${h.toUpperCase()}`;
}

function describe(a: BrandJson, b: BrandJson): string {
  const out: string[] = [];
  if (a.channel?.name !== b.channel.name) out.push(`channel "${b.channel.name}"`);
  if (a.channel?.language !== b.channel.language) out.push(`language ${b.channel.language}`);
  if (a.look.brand !== b.look.brand) out.push(`accent ${b.look.brand} (+ scale 25–900, bar, stage)`);
  if (JSON.stringify(a.logo) !== JSON.stringify(b.logo)) out.push(`logo ${b.logo.enabled ? 'on' : 'off'}, sting ${b.logo.sting ? 'on' : 'off'}`);
  if (a.typography.family !== b.typography.family) out.push(`font "${b.typography.family}"`);
  return out.join(', ') || 'updated';
}

function fontFiles(): string[] {
  return fs.existsSync(FONTS) ? fs.readdirSync(FONTS).filter((f) => FONT_EXT.includes(path.extname(f).toLowerCase())) : [];
}

/** Same rules as remotion/lib/fonts.ts */
function weightOf(name: string): string {
  const n = name.toLowerCase();
  if (/variable|wght|(^|[^a-z])(var|vf)([^a-z]|$)/.test(n)) return '100 900';
  const rules: Array<[RegExp, string]> = [
    [/thin|hairline/, '100'], [/extra-?light|ultra-?light/, '200'], [/light/, '300'], [/semi-?bold|demi-?bold/, '600'],
    [/extra-?bold|ultra-?bold/, '800'], [/black|heavy/, '900'], [/bold/, '700'], [/medium/, '500'],
  ];
  return rules.find(([re]) => re.test(n))?.[1] ?? '400';
}

/** SVG stays as it is; PNG/JPG/WebP is embedded in an SVG so the fixed .svg imports keep working. */
async function toSvg(file: string, opts: { square?: boolean } = {}): Promise<string> {
  const abs = path.resolve(expandHome(file));
  if (!fs.existsSync(abs)) throw new Error(`Not found: ${file}`);
  const ext = path.extname(abs).toLowerCase();
  if (ext === '.svg') {
    const svg = fs.readFileSync(abs, 'utf8');
    if (!/<svg[\s>]/i.test(svg)) throw new Error(`${file} is not an SVG.`);
    if (!/viewBox=/i.test(svg)) log.warn(`${path.basename(abs)} has no viewBox – it may not scale cleanly.`);
    return svg;
  }
  const mime = IMAGE_MIME[ext];
  if (!mime) throw new Error(`${file}: only .svg, .png, .jpg or .webp.`);
  const { w, h } = await imageSize(abs);
  const data = `data:${mime};base64,${fs.readFileSync(abs).toString('base64')}`;
  if (opts.square) {
    // avatar: square, cropped to the center (components draw it as a circle)
    const s = Math.min(w, h);
    return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${s}" height="${s}" viewBox="0 0 ${s} ${s}">${GENERATED}<image width="${w}" height="${h}" x="${(s - w) / 2}" y="${(s - h) / 2}" href="${data}" xlink:href="${data}"/></svg>`;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${GENERATED}<image width="${w}" height="${h}" href="${data}" xlink:href="${data}"/></svg>`;
}

async function imageSize(file: string): Promise<{ w: number; h: number }> {
  if (!hasBinary('ffprobe')) throw new Error('ffprobe missing (brew install ffmpeg) – needed to read the image size.');
  const res = await runOrThrow('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'json', file], `ffprobe ${file}`);
  const s = (JSON.parse(res.stdout) as { streams?: Array<{ width?: number; height?: number }> }).streams?.[0];
  if (!s?.width || !s?.height) throw new Error(`Could not read the size of ${file}.`);
  return { w: s.width, h: s.height };
}

function initialOf(name: string): string {
  return ([...name.trim()][0] ?? '?').toUpperCase();
}

function escapeXml(s: string): string {
  return s.replace(/[<>&"']/g, (c) => `&#${c.charCodeAt(0)};`);
}

function initialAvatar(name: string, accent: string): string {
  const ch = initialOf(name).replace(/[<>&"']/g, (c) => `&#${c.charCodeAt(0)};`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">${GENERATED}<circle cx="128" cy="128" r="128" fill="${accent}"/><text x="128" y="128" dy="0.35em" text-anchor="middle" font-family="Helvetica, Arial, sans-serif" font-weight="600" font-size="128" fill="#FFFFFF">${ch}</text></svg>`;
}

// ── color scale in OKLab (accent = 600) ──

type Lab = [number, number, number];

function primaryScale(accent: string): Record<string, string> {
  // how far each step moves from the accent towards white / black (tuned against the example blue scale)
  const TO_WHITE: Record<string, number> = { '25': 0.965, '50': 0.93, '100': 0.8, '200': 0.66, '300': 0.48, '400': 0.3, '500': 0.14 };
  const TO_BLACK: Record<string, number> = { '700': 0.11, '800': 0.24, '900': 0.33 };
  const a = hexToOklab(accent);
  const mix = (b: Lab, t: number): Lab => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
  const white = hexToOklab('#FFFFFF');
  const black = hexToOklab('#000000');
  const out: Record<string, string> = {};
  for (const step of ['25', '50', '100', '200', '300', '400', '500', '600', '700', '800', '900']) {
    if (step === '600') out[step] = accent;
    else if (step in TO_WHITE) out[step] = oklabToHex(mix(white, TO_WHITE[step]));
    else out[step] = oklabToHex(mix(black, TO_BLACK[step]));
  }
  return out;
}

function hexToOklab(hex: string): Lab {
  const n = parseInt(hex.slice(1), 16);
  const lin = (c: number) => {
    const v = c / 255;
    return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
  };
  const [r, g, b] = [lin((n >> 16) & 255), lin((n >> 8) & 255), lin(n & 255)];
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}

function oklabToHex([L, A, B]: Lab): string {
  const l = Math.pow(L + 0.3963377774 * A + 0.2158037573 * B, 3);
  const m = Math.pow(L - 0.1055613458 * A - 0.0638541728 * B, 3);
  const s = Math.pow(L - 0.0894841775 * A - 1.291485548 * B, 3);
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const enc = (v: number) => {
    const c = Math.min(1, Math.max(0, v));
    const g = c <= 0.0031308 ? c * 12.92 : 1.055 * Math.pow(c, 1 / 2.4) - 0.055;
    return Math.round(g * 255).toString(16).padStart(2, '0');
  };
  return `#${rgb.map(enc).join('')}`.toUpperCase();
}
